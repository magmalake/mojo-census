#!/bin/sh
# Several programs in one binary, which runs the program its name says,
# `basename "$0"`, as that program's own binary would. The library code they
# share (morca, iceberg, parquet...) is compiled once, not once per program,
# and is in the image once.
#
#   scripts/multicall.sh BINARY BIN_DIR PIPELINES_DIR PROGRAM.mojo... \
#       [-- mojo build flags...]
#
# writes BIN_DIR/BINARY and, for each program, a symbolic link to it:
# BIN_DIR/morca for bin/scheduler.mojo (the two lines calling morca.command),
# BIN_DIR/<name> for any other bin/<name>.mojo and PIPELINES_DIR/<name> for
# pipelines/<name>.mojo. PIPELINES_DIR is BIN_DIR or a directory beside it
# (the image's /opt/morca/bin and /opt/morca/pipelines). Each program keeps
# its argv, `argv()[0]` included, so its subcommands, exit codes and what
# morca reads of it (describe, locate, morca_maintain beside morca, the
# DISTA_ROLE re-exec) are those of its own binary. Run under its own name,
# or copied under another, BINARY runs none of them and says so: link it.
#
# Each program's file is imported as a module, so its name must be a valid
# one and not that of a module in src/; BINARY should have a `-`, which no
# module name has. `-I src` is added when there is a src/. Run inside
# `pixi run`.
set -eu
binary=$1
bin=$2
pipelines=$3
shift 3
progs=""
while [ $# -gt 0 ] && [ "$1" != -- ]; do
    progs="$progs $1"
    shift
done
[ $# -gt 0 ] && shift
gen=$(mktemp -d "${TMPDIR:-/tmp}/multicall.XXXXXX")
trap 'rm -rf "$gen"' EXIT
# A module name no program has.
main=$gen/multicall_main.mojo
name_of() {
    n=$(basename "$1" .mojo)
    [ "$1" = bin/scheduler.mojo ] && n=morca
    echo "$n"
}
{
    echo '"""Generated by scripts/multicall.sh: the program basename(argv[0])'
    echo 'names."""'
    echo
    echo 'from std.sys import argv'
    echo
    for f in $progs; do
        m=$(basename "$f" .mojo)
        echo "from $m import main as ${m}__main"
    done
    echo
    echo
    echo 'def main() raises:'
    echo '    var me = String(argv()[0])'
    echo '    var slash = me.rfind("/")'
    echo '    var name = String(me[byte = slash + 1 :]) if slash >= 0 else me'
    names=""
    kw=if
    for f in $progs; do
        n=$(name_of "$f")
        names="$names $n"
        echo "    $kw name == \"$n\":"
        echo "        $(basename "$f" .mojo)__main()"
        kw=elif
    done
    echo '    else:'
    echo "        raise Error(name, \": not a program of this binary; link it as one of:$names\")"
} > "$main"
inc="-I bin -I pipelines"
[ -d src ] && inc="$inc -I src"
mkdir -p "$bin" "$pipelines"
rm -f "$bin/$binary"
mojo build $inc "$@" "$main" -o "$bin/$binary"
if [ "$pipelines" = "$bin" ]; then to=$binary; else to=../$(basename "$bin")/$binary; fi
for f in $progs; do
    n=$(name_of "$f")
    case $f in
    pipelines/*) rm -f "$pipelines/$n" && ln -s "$to" "$pipelines/$n" ;;
    *) rm -f "$bin/$n" && ln -s "$binary" "$bin/$n" ;;
    esac
done
